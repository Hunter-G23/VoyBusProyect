import { test, expect } from '@playwright/test';
import { login } from './helpers';
import type { Line, Route, Stop } from '../front/src/types';
test('nueve requisitos integrados, persistencia y errores recuperables', async ({ page, browser }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Líneas', exact: true })).toBeVisible();
  await expect(page.getByText('Tu sesión venció.', { exact: false })).toHaveCount(0);
  const lines: Line[] = (await (await page.request.get('http://localhost:3001/api/red/lineas?todas=1')).json()).lineas;
  const line = lines.find(item => item.codigo === '102')!;
  const routes: Route[] = (await (await page.request.get(`http://localhost:3001/api/red/lineas/${line.id}/recorridos`)).json()).recorridos;
  const route = routes.find(item => !item.variante)!;
  const catalogStops: Stop[] = (await (await page.request.get(`http://localhost:3001/api/red/recorridos/${route.id}/paraderos`)).json()).paraderos;
  await page.getByRole('button', { name: /^102,/ }).click();
  await page.getByRole('radio').first().click();
  await expect(page.getByTestId('ordered-stops').getByText(catalogStops[0].codigo, { exact: true })).toBeVisible();
  await expect(page.getByTestId('ordered-stops').getByText(catalogStops[2].codigo, { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Ir a mi viaje', exact: true }).click();
  await page.getByRole('button', { name: 'Ingresar o crear cuenta', exact: true }).click();
  await page.getByRole('button', { name: 'Crear una cuenta', exact: true }).click();
  const email = `integrado-${testInfo.project.name}-${Date.now()}@example.test`;
  await page.getByLabel('Nombre', { exact: true }).fill('Pasajero Integrado');
  await page.getByLabel('Correo electrónico', { exact: true }).fill(email);
  await page.getByLabel('Contraseña', { exact: true }).fill('VoyBusDemo2026!');
  await page.getByLabel('Confirmar contraseña').fill('distinta');
  await page.getByRole('button', { name: 'Crear cuenta de pasajero', exact: true }).click();
  await expect(page.getByText('Las contraseñas deben coincidir.', { exact: true })).toBeVisible();
  await page.getByLabel('Confirmar contraseña').fill('VoyBusDemo2026!');
  await page.getByRole('button', { name: 'Crear cuenta de pasajero', exact: true }).click();
  await expect(page.getByText('Tu cuenta está creada. Ingresa con tu correo y contraseña.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Ingresar', exact: true }).last().click();
  await expect(page.getByRole('heading', { name: 'Agrega una foto', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Omitir', exact: true }).click();
  await expect(page.getByText('Vincula tu vehículo', { exact: true })).toBeVisible();
  await page.getByLabel('Código del vehículo', { exact: true }).fill('BUS999');
  await page.getByRole('button', { name: 'Vincular vehículo', exact: true }).click();
  await expect(page.getByText('No encontramos un servicio activo para ese código.', { exact: true })).toBeVisible();
  await page.getByLabel('Código del vehículo', { exact: true }).fill('BUS001');
  await page.getByRole('button', { name: 'Vincular vehículo', exact: true }).click();
  await expect(page.getByLabel('Paso 2: Destino, En curso', { exact: true })).toBeVisible();
  const current = (await (await page.request.get('http://localhost:3001/api/viaje/actual')).json()).vinculo;
  expect(current.linea).toBe('102');
  const stops: Stop[] = (await (await page.request.get(`http://localhost:3001/api/red/recorridos/${current.recorrido_id}/paraderos`)).json()).paraderos;
  const passed = stops.find(stop => stop.posicion <= current.ultima_posicion)!;
  const destination = stops.find(stop => stop.posicion > current.ultima_posicion + 1)!;
  await expect(page.getByRole('radio', { name: `${passed.codigo}, ${passed.nombre}, ya pasó`, exact: true })).toBeDisabled();
  await page.getByRole('radio', { name: `${destination.codigo}, ${destination.nombre}`, exact: true }).click();
  let receiptId: number | undefined;
  await page.route('**/api/viaje/solicitudes', async route => {
    const response = await route.fetch(); receiptId = (await response.json()).solicitud.id; await route.abort('failed');
  }, { times: 1 });
  await page.getByRole('button', { name: `Solicitar parada en ${destination.nombre}`, exact: true }).click();
  await expect(page.getByText('Hay un envío sin confirmar.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Reintentar envío', exact: true }).click();
  await expect(page.getByText('Solicitud enviada', { exact: true })).toBeVisible();
  await expect(page.getByText(`Solicitud #${receiptId}`, { exact: false })).toBeVisible();
  const history = await (await page.request.get('http://localhost:3001/api/viaje/historial')).json();
  expect(history.solicitudes.filter((request: { id: number }) => request.id === receiptId)).toHaveLength(1);
  await page.screenshot({ path: testInfo.outputPath('pasajero.png'), fullPage: true });
  await page.reload(); await page.getByRole('tab', { name: 'Mi viaje', exact: true }).click();
  await expect(page.getByText(`Solicitud #${receiptId}`, { exact: false })).toBeVisible();
  await page.route('**/api/viaje/solicitudes/*', route => route.abort());
  await page.getByRole('button', { name: 'Actualizar seguimiento', exact: true }).click();
  await expect(page.getByText('Información sin actualizar.', { exact: false })).toBeVisible();
  await page.unroute('**/api/viaje/solicitudes/*');
  await page.getByRole('button', { name: 'Actualizar seguimiento', exact: true }).click();
  await expect(page.getByText('Información sin actualizar.', { exact: false })).toHaveCount(0);
  const context = await browser.newContext({ viewport: testInfo.project.name === 'mobile-web' ? { width: 390, height: 844 } : { width: 1280, height: 900 } });
  const driver = await context.newPage(); await driver.goto('http://localhost:8082'); await login(driver, 'conductor@example.test');
  await expect(driver.getByRole('heading', { name: 'Solicitudes de parada', exact: true })).toBeVisible();
  await expect(driver.getByText(`#${receiptId}`, { exact: true })).toBeVisible();
  await driver.screenshot({ path: testInfo.outputPath('conductor.png'), fullPage: true });
  await context.close(); expect(errors).toEqual([]);
});
